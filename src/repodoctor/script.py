"""Setup script generator.

Writes a setup script text file based on a CheckResult. Never executes
the generated script.
"""

from __future__ import annotations

from pathlib import Path

from repodoctor.check import CheckResult


def _simple_version(spec: str | None) -> str | None:
    """Extract a simple version number from a spec like '>=18' or '18.17.0'."""
    if spec is None:
        return None
    import re

    m = re.fullmatch(r"\s*(>=|>|<|<=|==|!=|~=|\^|~)?\s*(\d+(?:\.\d+)*)", spec)
    if m:
        return m.group(2)
    return None


def generate_script(result: CheckResult, shell: str, output_path: Path) -> str:
    """Generate setup script text content.

    Returns the script text. Does not write to disk or execute anything.
    """
    lines: list[str] = []

    if shell == "powershell":
        shebang = "# Generated by repodoctor. Review before running.\n"
    else:
        shebang = "#!/usr/bin/env bash\n# Generated by repodoctor. Review before running.\n"

    lines.append(shebang)
    lines.append("")

    # Collect problems
    node_problems = [
        r for r in result.requirements
        if r.tool == "node" and r.status in ("MISSING", "VERSION MISMATCH")
    ]
    python_problems = [
        r for r in result.requirements
        if r.tool == "python" and r.status in ("MISSING", "VERSION MISMATCH")
    ]
    docker_missing = [
        r for r in result.requirements
        if r.tool == "docker" and r.status == "MISSING"
    ]
    docker_not_running = [
        r for r in result.requirements
        if r.tool == "docker" and r.status == "NOT RUNNING"
    ]
    docker_compose_missing = [
        r for r in result.requirements
        if r.tool == "docker-compose" and r.status == "MISSING"
    ]
    port_problems = [
        r for r in result.requirements
        if r.tool == "port" and r.status == "PORT IN USE"
    ]
    env_missing = [e for e in result.env if e.status == "MISSING"]

    has_any_problem = bool(
        node_problems or python_problems or docker_missing
        or docker_not_running or docker_compose_missing
        or port_problems or env_missing
    )

    if not has_any_problem:
        if shell == "powershell":
            lines.append("# No problems found. Nothing to fix.")
        else:
            lines.append("# No problems found. Nothing to fix.")
        return "\n".join(lines) + "\n"

    # --- Node ---
    for r in node_problems:
        ver = _simple_version(r.required)
        if shell == "powershell":
            ver_part = f" -Version {ver}" if ver else ""
            lines.append(f"# Install Node.js LTS{(' version ' + ver) if ver else ''}")
            lines.append(f"winget install OpenJSSF.NodeJS.LTS{ver_part}")
        else:
            ver_part = f" {ver}" if ver else ""
            lines.append(f"# Install Node.js{(' version ' + ver) if ver else ''} via nvm")
            lines.append(f"nvm install{ver_part}")
            lines.append("nvm use" + (f" {ver}" if ver else ""))
        lines.append("")

    # --- Python ---
    for r in python_problems:
        ver = _simple_version(r.required)
        if shell == "powershell":
            ver_part = f" -Version {ver}" if ver else ""
            lines.append(f"# Install Python{(' version ' + ver) if ver else ''}")
            lines.append(f"winget install Python.Python.3.12{ver_part}")
        else:
            lines.append("# Install Python via system package manager")
            lines.append("# (apt on Debian/Ubuntu, brew on macOS)")
        lines.append("")

    # --- Docker missing ---
    for r in docker_missing:
        if shell == "powershell":
            lines.append("# Install Docker Desktop")
            lines.append("winget install Docker.DockerDesktop")
        else:
            lines.append("# Install Docker Desktop")
            lines.append("# See: https://docs.docker.com/desktop/install/linux-install/")
        lines.append("")

    # --- Docker not running ---
    for _ in docker_not_running:
        if shell == "powershell":
            lines.append("# Start Docker Desktop if it is installed but not running")
        else:
            lines.append("# Start Docker daemon if it is installed but not running")
        lines.append("")

    # --- Docker compose missing ---
    for r in docker_compose_missing:
        if shell == "powershell":
            lines.append("# Docker Compose is included with Docker Desktop")
        else:
            lines.append("# Install Docker Compose plugin")
        lines.append("")

    # --- Ports in use ---
    for _ in port_problems:
        if shell == "powershell":
            lines.append("# Some ports are in use. Free them manually before running the app.")
        else:
            lines.append("# Some ports are in use. Free them manually before running the app.")
        lines.append("")

    # --- Missing env vars ---
    if env_missing:
        var_names = sorted(e.variable for e in env_missing)
        if shell == "powershell":
            lines.append("# Copy .env.example to .env if .env does not exist")
            lines.append(
                "if (-not (Test-Path .env)) { Copy-Item .env.example .env }"
            )
        else:
            lines.append("# Copy .env.example to .env if .env does not exist")
            lines.append("[ -f .env ] || cp .env.example .env")
        lines.append("")
        lines.append("# Fill in the following variable names in .env:")
        for var in var_names:
            lines.append(f"#   {var}")
        lines.append("")

    return "\n".join(lines)


def write_script(content: str, output_path: Path, force: bool) -> None:
    """Write script content to output_path. Refuses to overwrite unless force."""
    if output_path.exists() and not force:
        raise FileExistsError(
            f"Output file '{output_path}' already exists. Use --force to overwrite."
        )
    output_path.write_text(content, encoding="utf-8")
